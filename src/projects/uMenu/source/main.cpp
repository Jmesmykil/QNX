// W17-FIX2: atomic completion flag for the background theme-seed thread.
// true  = thread has finished (or was never needed — all bundles up-to-date).
// false = thread is still running.
// Checked by Settings → Themes before first theme-switch in this session.
std::atomic<bool> g_qos_themes_bg_done { false };

// W17-FIX2: background wrapper that runs EnsureQosThemesOnSd off the main thread.
// W18-DIAG: temporarily unused while the bg-thread vs main-thread SD I/O race is
// eliminated as a variable.  Kept for the v3.6 boot-speed refactor.
[[maybe_unused]] static void BackgroundEnsureQosThemesOnSd() {
    const bool refreshed = EnsureQosThemesOnSd();
    if (refreshed) {
        UL_LOG_INFO("W17-FIX2: BG theme-seed: bundles upgraded — invalidating cache");
        ul::cfg::RemoveActiveThemeCache();
    }
    g_qos_themes_bg_done.store(true, std::memory_order_release);
}

