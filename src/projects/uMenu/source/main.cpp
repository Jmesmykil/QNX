    // EARLY-TRACE (v3.7.52, pre-fsdev pinpoint): a raw-FsFileSystem writer that
    // works the instant fsInitialize() returns — BEFORE fsdevMountSdmc() — unlike
    // BtWrite which needs the libnx-mounted sdmc. Each call opens+writes+closes its
    // own session so it survives a hang on the very next line. Purpose: locate
    // exactly where a 2nd-in-session uMenu relaunch parks (its boot-trace is empty
    // = it dies before its first mounted-sdmc write). Reading umenu_early_trace.log:
    //   file ABSENT          -> parked in crt0/__libnx_init/smInitialize/fsInitialize
    //   "(a)" present, no BT  -> parked IN fsdevMountSdmc
    //   "(a)"+"(b)", no BT    -> parked in the boot-trace setup block (264-281)
    //   BT present            -> parked later (see umenu_boot_trace.log)
    static void EarlyTrace(const char *tag) {
        FsFileSystem fs;
        if(R_FAILED(fsOpenSdCardFileSystem(&fs))) return;
        fsFsCreateDirectory(&fs, "/ulaunch");                          // idempotent
        fsFsCreateFile(&fs, "/ulaunch/umenu_early_trace.log", 0, 0);   // idempotent
        FsFile file;
        if(R_SUCCEEDED(fsFsOpenFile(&fs, "/ulaunch/umenu_early_trace.log",
                                    FsOpenMode_Write | FsOpenMode_Append, &file))) {
            s64 sz = 0;
            fsFileGetSize(&file, &sz);
            char line[160];
            const int n = snprintf(line, sizeof(line), "[EARLY] %s\n", tag);
            if(n > 0) {
                fsFileWrite(&file, sz, line, (u64)n, FsWriteOption_Flush);
            }
            fsFileClose(&file);
        }
        fsFsClose(&fs);
    }

    void __appInit() {
        UL_RC_ASSERT(smInitialize());

        UL_RC_ASSERT(fsInitialize());
        EarlyTrace("(a) fsInitialize OK — pre-fsdevMountSdmc");
        UL_RC_ASSERT(fsdevMountSdmc());
        EarlyTrace("(b) fsdevMountSdmc OK");

        // v2.0.3-A3: ensure sdmc:/switch/ exists at boot. HBmenu currently
        // creates this directory on first run; once HBmenu is removed (P-07
        // in the HBmenu deletion checklist), uMenu must own the create.
        // Idempotent: EEXIST on populated SD ~0.5-1ms; ignored.
        mkdir("sdmc:/switch/", 0777);

        // BOOT-TRACE: arm the flag once sdmc is mounted so every subsequent
        // BtWrite call can open the log.  access() is safe at this point.
        // The flag file is sdmc:/ulaunch/debug.flag (same dev-mode gate used
        // by uSystem's HomeTrace and uMenu's dev-mode paths).
        {
            mkdir("sdmc:/ulaunch", 0777);   // idempotent
            g_bt_enabled = (access("sdmc:/ulaunch/debug.flag", F_OK) == 0);
            if (g_bt_enabled) {
                // Stamp the trace file with a boot separator so successive
                // reboots don't blur together.
                FILE *f = fopen("sdmc:/ulaunch/umenu_boot_trace.log", "ab");
                if (f) {
                    const char sep[] = "\n--- uMenu __appInit ENTRY ---\n";
                    fwrite(sep, sizeof(sep) - 1, 1, f);
                    fclose(f);
                }
            }
        }
        BT("__appInit ENTRY — smInitialize+fsdevMountSdmc OK");

        UL_RC_ASSERT(timeInitialize());
        __libnx_init_time();
        BT("timeInitialize OK");

        ul::InitializeLogging("uMenu");
        ul::tel::Init("uMenu");
        BT("InitializeLogging + tel::Init OK");
        // Flush the async SPSC telemetry queue on normal C-library exit (covers
        // the Home-button-press-from-library-applet path which calls C atexit
        // handlers before __appExit).  Crashes that skip atexit still get
        // synchronous WARN/CRIT entries via EmitSync; BOOT markers are already
        // written synchronously in tel::Init.  This captures best-effort INFO
        // messages accumulated since the last periodic flush.
        std::atexit([] { ul::tel::Flush(); });
        UL_LOG_INFO("Alive!");

        UL_RC_ASSERT(setsysInitialize());
        g_svc_lh_setsys_ = UL_LEDGER_TRACK(
            ::ul::menu::qdesktop::QdResKind::Service, "main:setsys", 0);
        UL_RC_ASSERT(setInitialize());

        UL_RC_ASSERT(setsysGetFirmwareVersion(&g_FirmwareVersion));
        hosversionSet(MAKEHOSVERSION(g_FirmwareVersion.major, g_FirmwareVersion.minor, g_FirmwareVersion.micro) | BIT(31));

        // W18-RACE-RETRY: appletInitialize() can return svc::SessionClosed
        // (0xF601 / 2001-0123) when the previous uMenu session crashed without
        // cleanly releasing the SystemApplet session.  Atmosphère's am
        // sysmodule needs a few hundred milliseconds to re-establish the
        // session in that case.  A plain UL_RC_ASSERT here panics on the
        // very next boot after any crash and leaves the user with a black
        // screen until they hard power-cycle.  Retry up to 8 times with
        // 100 ms backoff before giving up — gives am ~800 ms to recover.
        BT("BEFORE appletInitialize (retry loop)");
        {
            Result rc_applet = 0;
            for (int i = 0; i < 8; ++i) {
                rc_applet = appletInitialize();
                if (R_SUCCEEDED(rc_applet)) break;
                UL_LOG_WARN("appletInitialize attempt %d/%d rc=0x%08X — "
                            "retrying in 100ms",
                            i + 1, 8, rc_applet);
                svcSleepThread(100'000'000ULL);  // 100 ms
            }
            UL_RC_ASSERT(rc_applet);
        }
        BT("appletInitialize OK");
        // v2.0.3-A1 first-paint telemetry: capture tick immediately after
        // appletInitialize() so the t_appinit -> first-paint delta excludes
        // pre-applet libnx setup (sm/fs/time) which is invariant across boots.
        g_qos_boot_t_appinit_ticks = armGetSystemTick();
        BT("BEFORE hidInitialize");
        UL_RC_ASSERT(hidInitialize());
        BT("hidInitialize OK");

        // W18-RACE-RETRY: same protection for ns + account — those are the
        // other sysmodule sessions that can be transitionally closed in the
        // same crash-recovery window.
        BT("BEFORE accountInitialize (retry loop)");
        {
            Result rc_acc = 0;
            for (int i = 0; i < 8; ++i) {
                rc_acc = accountInitialize(AccountServiceType_System);
                if (R_SUCCEEDED(rc_acc)) break;
                UL_LOG_WARN("accountInitialize attempt %d/%d rc=0x%08X",
                            i + 1, 8, rc_acc);
                svcSleepThread(100'000'000ULL);
            }
            UL_RC_ASSERT(rc_acc);
        }
        BT("accountInitialize OK");
        g_svc_lh_account_ = UL_LEDGER_TRACK(
            ::ul::menu::qdesktop::QdResKind::Service, "main:account", 0);
        // W18-RACE-RETRY: ns can also hit SessionClosed in the same window.
        BT("BEFORE nsInitialize (retry loop)");
        {
            Result rc_ns = 0;
            for (int i = 0; i < 8; ++i) {
                rc_ns = nsInitialize();
                if (R_SUCCEEDED(rc_ns)) break;
                UL_LOG_WARN("nsInitialize attempt %d/%d rc=0x%08X",
                            i + 1, 8, rc_ns);
                svcSleepThread(100'000'000ULL);
            }
            UL_RC_ASSERT(rc_ns);
        }
        BT("nsInitialize OK");
        g_svc_lh_ns_ = UL_LEDGER_TRACK(
            ::ul::menu::qdesktop::QdResKind::Service, "main:ns", 0);
        BT("BEFORE nssuInitialize");
        UL_RC_ASSERT(nssuInitialize());
        BT("BEFORE avmInitialize");
        UL_RC_ASSERT(avmInitialize());
        BT("BEFORE ul::net::Initialize");
        UL_RC_ASSERT(ul::net::Initialize());
        BT("BEFORE psmInitialize");
        UL_RC_ASSERT(psmInitialize());
        BT("psmInitialize OK");
        g_svc_lh_psm_ = UL_LEDGER_TRACK(
            ::ul::menu::qdesktop::QdResKind::Service, "main:psm", 0);

        ul::menu::SetControlEntryLoadFunction(MenuControlEntryLoadFunction);
        BT("BEFORE bt::InitializeBluetoothManager");
        ul::menu::bt::InitializeBluetoothManager();
        BT("bt::InitializeBluetoothManager OK");

        // v3.1 Phase 2 Task 6's `viInitialize(Manager)` was REMOVED 2026-05-19
        // per uMenu audit F5.3.  Original intent: claim vi:m before
        // __nx_win_init so the BG-indirect probe could use vi:m-only
        // primitives.  We pivoted that capture path to a uSystem-owned
        // Tesla-style overlay (Tesla overlay model — see CHANGELOG v3.0.2),
        // so uMenu no longer needs vi:m.  Letting libnx's __nx_win_init pick
        // the default service type per applet kind saves 1–3 ms of IPC on
        // every boot (and avoids the vi:m permission-denial retry on HW
        // where the cap isn't granted).
        //
        // If a future feature in uMenu needs vi:m, re-add a viInitialize call
        // here BEFORE __nx_win_init (libnx's vi globals are sticky on first
        // init).

        // NRO-RELAUNCH VI-LAYER FIX (2026-06-19):
        //
        // When uMenu is relaunched after a library-applet NRO exits, the
        // compositor tears down the NRO's vi layer asynchronously.  If the NRO
        // was itself a library applet (the second-applet case), the compositor
        // may not have freed the managed-layer slot by the time __nx_win_init()
        // runs.  libnx's __nx_win_init calls viInitialize(System) then
        // viCreateManagedLayer + nwindowCreateFromLayer and throws a fatal
        // LibnxError_BadGfxInit if viCreateManagedLayer fails.
        //
        // On a CLEAN boot uMenu is the first library applet so the compositor
        // slot is always free — no hang.  On NRO-relaunch the slot may still
        // be in teardown (observed: ~80–500 ms on Erista), causing
        // viCreateManagedLayer inside __nx_win_init to block until the slot is
        // freed OR return an error that libnx escalates to a fatal.
        //
        // uSystem's 500 ms settle sleep (uSystem main.cpp:1783) usually covers
        // the teardown window, but the compositor can still be draining when
        // uMenu's __appInit fires because __appInit runs during ECS launch
        // registration, BEFORE the compositor acknowledges the new applet.
        //
        // DIAGNOSTIC STRATEGY: trace BEFORE and AFTER __nx_win_init so the
        // boot-trace log shows whether the hang is inside __nx_win_init (most
        // likely) or elsewhere.  If the hang IS inside __nx_win_init, the
        // "AFTER" line will never appear on a relaunch-black test.
        //
        // FIX ATTEMPT: pre-probe viInitialize(System) before __nx_win_init so
        // we can log an explicit vi result code rather than hitting the libnx
        // fatal handler (which writes nothing to our trace log).  If
        // viInitialize succeeds, proceed.  viInitialize is idempotent if the
        // service was already open (libnx tracks a global open count), so
        // __nx_win_init calling it again internally is safe.  This probe does
        // NOT retry — it only informs the trace; the retry logic is in uSystem.
        BT("BEFORE viInitialize(System) probe");
        {
            const Result vi_rc = viInitialize(ViServiceType_System);
            char vi_buf[64];
            ::snprintf(vi_buf, sizeof(vi_buf),
                "viInitialize(System) probe rc=0x%08X", vi_rc);
            BT(vi_buf);
            // If the probe succeeded we now hold one extra reference.
            // Close it immediately — __nx_win_init opens its own reference
            // and we must not interfere with its refcount management.
            if (R_SUCCEEDED(vi_rc)) {
                viExit();
                BT("viExit() (probe ref released)");
            }
        }

        BT("BEFORE __nx_win_init (vi managed-layer creation)");
        __nx_win_init();
        BT("__nx_win_init RETURNED OK — display layer acquired");
    }

    void __appExit() {
        // W7: flush and close the perf log before any service teardown so the
        // final rows land on disk before sdmc: is unmounted.
        ::ul::menu::qdesktop::QdPerfLogger::Instance().Shutdown();

        // W6-LEDGER: untrack process-lifetime services before they exit.
        UL_LEDGER_UNTRACK(g_svc_lh_psm_);     g_svc_lh_psm_     = 0;
        UL_LEDGER_UNTRACK(g_svc_lh_ns_);      g_svc_lh_ns_      = 0;
        UL_LEDGER_UNTRACK(g_svc_lh_account_); g_svc_lh_account_ = 0;
        UL_LEDGER_UNTRACK(g_svc_lh_setsys_);  g_svc_lh_setsys_  = 0;
        ul::tel::Shutdown();

        ul::audio::FinalizeSystemVolume();
        ul::menu::smi::sf::FinalizePrivateService();

        // Exit RomFs manually, since we also initialized it manually
        romfsExit();

        UL_LOG_INFO("Goodbye!");

        __nx_win_exit();

        ul::menu::bt::FinalizeBluetoothManager();
        setExit();
        setsysExit();
        psmExit();
        ul::net::Finalize();
        avmExit();
        nssuExit();
        nsExit();
        accountExit();

        timeExit();

        hidExit();

        appletExit();

        fsdevUnmountAll();
        fsExit();

        smExit();
    }

