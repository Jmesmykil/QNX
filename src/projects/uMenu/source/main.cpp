// uMenu procedure: read sent storages, initialize RomFs (externally), load config and other stuff, finally create the renderer and start the UI

int main() {
    // v2.0.3-A1 first-paint telemetry: t_main captures the earliest user-code
    // entry point. Delta(t_main - t_appinit_ticks) approximates the cost of
    // libnx-time wiring + the static InitializeSettings cascade.
    g_qos_boot_t_main_ticks = armGetSystemTick();
    InitializeSettings();

    // W18-INPUT-STORAGE-RETRY: when uMenu is launched as the qlaunch override,
    // its parent (uSystem) is supposed to push two storages — LibAppletArgs
    // carrying the MenuStartMode, then a SystemStatus blob.  If uSystem is
    // slow to populate them (post-crash recovery boot, AM races, cold-start
    // ordering), appletPopInData returns 0x1159 (libnx::NotInitialized).
    // The previous unconditional UL_RC_ASSERT here turned that transient
    // race into a hard crash that bounced uMenu back to Atmosphère's fatal
    // screen.  Retry with a short backoff, then fall back to MainMenu +
    // zeroed SystemStatus so the user gets a usable desktop rather than a
    // bricked launcher.
    {
        Result rc_sm = 0;
        for(int i = 0; i < 16; ++i) {
            rc_sm = ul::menu::am::ReadStartMode(g_StartMode);
            if(R_SUCCEEDED(rc_sm)) {
                break;
            }
            UL_LOG_WARN("ReadStartMode attempt %d/%d rc=0x%08X — retrying in 100ms", i + 1, 16, rc_sm);
            svcSleepThread(100'000'000ULL);
        }
        if(R_FAILED(rc_sm) || g_StartMode == ul::smi::MenuStartMode::Invalid) {
            UL_LOG_WARN("ReadStartMode exhausted retries (rc=0x%08X, mode=%u) — defaulting to MainMenu", rc_sm, (u32)g_StartMode);
            g_StartMode = ul::smi::MenuStartMode::MainMenu;
        }
    }

    // Information sent as an extra storage to uMenu
    {
        Result rc_ss = 0;
        for(int i = 0; i < 16; ++i) {
            rc_ss = ul::menu::am::ReadFromInputStorage(&g_GlobalSettings.system_status, sizeof(g_GlobalSettings.system_status));
            if(R_SUCCEEDED(rc_ss)) {
                break;
            }
            UL_LOG_WARN("ReadFromInputStorage(system_status) attempt %d/%d rc=0x%08X — retrying in 100ms", i + 1, 16, rc_ss);
            svcSleepThread(100'000'000ULL);
        }
        if(R_FAILED(rc_ss)) {
            UL_LOG_WARN("ReadFromInputStorage(system_status) exhausted retries (rc=0x%08X) — defaulting to zeroed SystemStatus", rc_ss);
            g_GlobalSettings.system_status = {};
        }
    }
    g_GlobalSettings.initial_last_menu_index = g_GlobalSettings.system_status.last_menu_index;
    g_GlobalSettings.initial_last_menu_fs_path = g_GlobalSettings.system_status.last_menu_fs_path;
    UL_LOG_INFO("Start mode: %d, last path: '%s', last fs path: '%s', last menu index: %d", (u32)g_StartMode, g_GlobalSettings.system_status.last_menu_path, g_GlobalSettings.system_status.last_menu_fs_path, g_GlobalSettings.system_status.last_menu_index);

    // Check if our RomFs data exists...
    if(!ul::fs::ExistsFile(ul::MenuRomfsFile)) {
        UL_RC_ASSERT(ul::ResultRomfsNotFound);
    }

    // Try to mount it
    UL_RC_ASSERT(romfsMountFromFsdev(ul::MenuRomfsFile, 0, "romfs"));

    // Register handlers for HOME button press detection
    ul::menu::am::RegisterLibnxLibappletHomeButtonDetection();
    ul::menu::ui::QuickMenu::RegisterHomeButtonDetection();

    // v2.0.3-A1 first-paint telemetry: t_premain captures the moment before
    // MenuApplication::OnLoad runs (renderer init + theme + BGM + UI). Delta
    // (first-OnRender - t_premain) is the qd_DesktopIcons hot path on its own.
    g_qos_boot_t_premain_ticks = armGetSystemTick();
    MainLoop();

    return 0;
}
