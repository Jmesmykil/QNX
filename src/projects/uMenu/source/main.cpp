// ---------------------------------------------------------------------------
// BOOT-TRACE (2026-06-19): diagnostic for NRO-relaunch black-screen hang.
//
// When sdmc:/ulaunch/debug.flag exists, every major startup step writes one
// line to sdmc:/ulaunch/umenu_boot_trace.log using fopen("ab")+fwrite+fflush
// +fclose (immediate-flush, zero buffering).  The LAST line present after a
// relaunch-black reveals the exact hang point.
//
// Gate: checked once at process start.  Zero overhead when the flag is absent
// because g_bt_enabled is set by checking access() in __appInit before any
// other logging runs.  The trace predates UL_LOG_INFO so it's useful even
// when the log writer itself is suspect.
// ---------------------------------------------------------------------------
static bool g_bt_enabled = false;

// BtWrite — core trace primitive.  Called at every instrumented checkpoint.
// Uses raw POSIX file I/O so it works even if fsdev or stdio is partially
// initialised.  We fflush+fclose after every write so the log survives a
// hang/crash immediately after the call.
static void BtWrite(const char *tag) {
    if (!g_bt_enabled) return;
    FILE *f = fopen("sdmc:/ulaunch/umenu_boot_trace.log", "ab");
    if (!f) return;
    char buf[160];
    int n = ::snprintf(buf, sizeof(buf),
        "[BOOT_TRACE tick=%lu] %s\n",
        static_cast<unsigned long>(armGetSystemTick()), tag);
    if (n > 0) {
        fwrite(buf, static_cast<size_t>(n), 1, f);
        fflush(f);
    }
    fclose(f);
}

// Convenience: BtWrite + UL_LOG_INFO (called after logging is available).
#define BT(tag) BtWrite(tag)

