// v2.9.9 — file-size helper used by EnsureQosThemesOnSd to detect stale SD
// .ultheme bundles.  Returns -1 if the file is missing or stat fails.
static long long QosFileSize(const char *path) {
    struct stat st;
    if (stat(path, &st) != 0) return -1;
    return static_cast<long long>(st.st_size);
}

// v2.7.0 — first-boot copy of the 10 Q OS .ultheme bundles from romfs:/themes/
// to sdmc:/ulaunch/themes/. Each bundle was generated by
// scripts/generate-qos-theme-icons.py and baked into romfs.bin. They live
// as real .ultheme files on the user's SD so they show up in the Themes menu
// via the standard cfg::FindThemes() scan (no parallel in-binary registry).
//
// v2.9.9 — Upgrade detection.  Previously the seed-only-if-missing guard
// (access(dst, F_OK) == 0 → skip) meant that older shipped bundles (v2.9.4
// stubs with only 3 files inside the zip) STAYED on SD across fork updates,
// and CacheActiveTheme would extract those stale stubs every time the user
// applied a theme — leaving the cache without per-category folder PNGs or
// HotCornerQ.png and forcing fallback to Glass for every other theme.
// Fix: compare romfs source size to SD destination size; if they differ,
// back up the SD copy as `.qos-prev.<size>.ultheme` and re-seed from romfs.
// User customisation: user themes use NEW filenames (`my-theme.ultheme`,
// already on SD), so the `q-os-*.ultheme` namespace is owned by Q OS and
// safe to refresh.
// Returns true if any q-os-*.ultheme bundle was refreshed (so the caller knows
// to invalidate the active theme cache and force a re-extract from the new
// bundle on the next EnsureCacheActiveTheme step).
static bool EnsureQosThemesOnSd() {
    static const char *const kQosThemes[] = {
        "q-os-0-q-os.ultheme",
        "q-os-1-neon.ultheme",
        "q-os-2-minimal.ultheme",
        "q-os-3-retro.ultheme",
        "q-os-4-cards.ultheme",
        "q-os-5-pastel.ultheme",
        "q-os-6-dark.ultheme",
        "q-os-7-gradient.ultheme",
        "q-os-8-blueprint.ultheme",
        "q-os-9-pixel.ultheme",
    };
    mkdir("sdmc:/ulaunch", 0777);
    mkdir("sdmc:/ulaunch/themes", 0777);
    bool any_written = false;
    for (const char *name : kQosThemes) {
        char dst[256];
        char src[256];
        std::snprintf(dst, sizeof(dst), "sdmc:/ulaunch/themes/%s", name);
        std::snprintf(src, sizeof(src), "romfs:/themes/%s", name);
        const long long src_sz = QosFileSize(src);
        const long long dst_sz = QosFileSize(dst);
        if (src_sz < 0) {
            UL_LOG_WARN("EnsureQosThemesOnSd: missing romfs source %s", src);
            continue;
        }
        const bool dst_exists = (dst_sz >= 0);
        if (dst_exists && dst_sz == src_sz) {
            // Same size = treat as identical content.  Skip silently.
            continue;
        }
        if (dst_exists) {
            // SD copy is a different size from the romfs copy — either a
            // stale older Q OS-shipped bundle or a user-edited variant.
            // Back it up before overwriting so nothing is irrecoverable.
            char bak[320];
            std::snprintf(bak, sizeof(bak),
                          "sdmc:/ulaunch/themes/%s.qos-prev.%lld.bak",
                          name, dst_sz);
            // Best-effort rename; if it fails we still proceed with seed
            // (so a broken SD copy doesn't permanently wedge the user out
            // of fresh Q OS themes).
            if (std::rename(dst, bak) != 0) {
                UL_LOG_WARN("EnsureQosThemesOnSd: backup rename %s -> %s "
                            "failed errno=%d (proceeding without backup)",
                            dst, bak, errno);
            } else {
                UL_LOG_INFO("EnsureQosThemesOnSd: backed up stale %s -> %s "
                            "(was %lld B, romfs source %lld B)",
                            dst, bak, dst_sz, src_sz);
            }
        }
        FILE *in = std::fopen(src, "rb");
        if (!in) {
            UL_LOG_WARN("EnsureQosThemesOnSd: cannot open romfs %s errno=%d",
                        src, errno);
            continue;
        }
        FILE *out = std::fopen(dst, "wb");
        if (!out) {
            UL_LOG_WARN("EnsureQosThemesOnSd: cannot create %s errno=%d",
                        dst, errno);
            std::fclose(in);
            continue;
        }
        char buf[65536];
        size_t n;
        while ((n = std::fread(buf, 1, sizeof(buf), in)) > 0) {
            std::fwrite(buf, 1, n, out);
        }
        std::fclose(out);
        std::fclose(in);
        any_written = true;
        UL_LOG_INFO("EnsureQosThemesOnSd: %s %s (%lld B)",
                    dst_exists ? "refreshed" : "seeded", dst, src_sz);
    }
    if (any_written) {
        fsdevCommitDevice("sdmc");
        UL_LOG_INFO("EnsureQosThemesOnSd: SD committed");
    }
    return any_written;
}

